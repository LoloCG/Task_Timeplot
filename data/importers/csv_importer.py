import csv
import math
import re
from datetime import datetime
from pathlib import Path

import pandas as pd


_COLUMNS = (
    "course", "period", "subject", "task_name",
    "start_time", "end_time", "time_spent_hrs", "finished",
)
_MAIN_KEY = ("course", "period", "subject", "task_name", "start_time")
_DATETIME_PATTERN = r"[0-9]{4}-[0-9]{2}-[0-9]{2}[ T][0-9]{2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]{1,6})?"


class CSVImporter:
    """Read and validate normalized main-data CSV files without instance state.
    
    Mostly generated by GPT-6.1SolH"""

    @classmethod
    def load_main_data_csv(cls, csv_path: str | Path) -> pd.DataFrame:
        """Return typed data without writes; invalid data raises ValueError.

        Data row numbers exclude the header. Text and local timestamps are
        preserved. File access errors propagate to the caller.
        """
        records = cls._read_records(Path(csv_path))
        records = [cls._convert_record(record, row_number)
                   for row_number, record in enumerate(records, start=1)]
        df = pd.DataFrame.from_records(records, columns=_COLUMNS)
        for column in ("start_time", "end_time"):
            df[column] = pd.to_datetime(df[column], errors="raise")

        duplicate_rows = df.index[df.duplicated(subset=list(_MAIN_KEY), keep=False)] + 1
        if len(duplicate_rows):
            raise ValueError(
                f"Duplicate main-data keys in data rows {duplicate_rows[:5].tolist()} "
                f"({len(duplicate_rows)} affected rows)."
            )
        return df

    @staticmethod
    def _read_records(path: Path) -> list[dict]:
        # Shouldnt this not be concern of other services upstream? unnecessary checking
        if path.suffix.lower() != ".csv":
            raise ValueError("Select a .csv file containing normalized main data.")

        records = []
        with path.open(encoding="utf-8-sig", newline="") as handle:
            reader = csv.reader(handle, strict=True)
            try:
                headers = next(reader, None)
                if headers is None:
                    raise ValueError("The CSV file is empty.")
                if len(headers) != len(_COLUMNS) or set(headers) != set(_COLUMNS):
                    raise ValueError(
                        f"Expected each CSV column exactly once: {', '.join(_COLUMNS)}; "
                        f"received {headers!r}."
                    )

                for row_number, values in enumerate(reader, start=1):
                    if len(values) != len(_COLUMNS):
                        raise ValueError(
                            f"Data row {row_number}: expected {len(_COLUMNS)} fields, got {len(values)}."
                        )
                    records.append(dict(zip(headers, values)))
            except csv.Error as exc:
                raise ValueError(
                    f"Malformed CSV near physical line {reader.line_num}: {exc}"
                ) from exc

        if not records:
            raise ValueError("The CSV file contains a header but no data rows.")
        return records

    @classmethod
    def _convert_record(cls, record: dict, row_number: int) -> dict:
        location = f"Data row {row_number}"
        for column, value in record.items():
            if not value.strip():
                raise ValueError(f"{location}, {column}: a value is required.")

        record = record.copy()
        for column in ("start_time", "end_time"):
            record[column] = cls._parse_datetime(record[column], f"{location}, {column}")
        if record["end_time"] < record["start_time"]:
            raise ValueError(f"{location}: end_time must not precede start_time.")

        record["time_spent_hrs"] = cls._parse_hours(record["time_spent_hrs"], location)
        value = record["finished"].lower()
        if value not in ("true", "false"):
            raise ValueError(
                f"{location}, finished: expected True or False, got {record['finished']!r}."
            )
        record["finished"] = value == "true"
        return record

    @staticmethod
    def _parse_datetime(value: str, location: str) -> datetime:
        if re.fullmatch(_DATETIME_PATTERN, value) is None:
            raise ValueError(
                f"{location}: expected a local ISO datetime "
                f"with seconds and up to six fractional digits, got {value!r}."
            )
        try:
            return datetime.fromisoformat(value)
        except ValueError as exc:
            raise ValueError(f"{location}: invalid datetime {value!r}.") from exc

    @staticmethod
    def _parse_hours(value: str, location: str) -> float:
        try:
            hours = float(value)
        except ValueError as exc:
            raise ValueError(
                f"{location}, time_spent_hrs: invalid number {value!r}."
            ) from exc
        if not math.isfinite(hours) or hours < 0:
            raise ValueError(
                f"{location}, time_spent_hrs: expected finite hours >= 0, got {value!r}."
            )
        return hours

